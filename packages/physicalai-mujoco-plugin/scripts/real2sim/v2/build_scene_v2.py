def _resistor_parts(scale: float, mass: float) -> list[str]:
    """The resistor's collision as cap / waist / cap cylinders along its long axis (30 / 40 / 30 % of the length), radii
    from the CAD hull's section heights (so a lying one rests as its visual does), masses by volume."""
    import mujoco
    xml = f'<mujoco><compiler meshdir="{plugin / "urdf/scenes/bucket_sort/assets"}"/><asset><mesh name="h" file="resistor_hull.msh" scale="{scale} {scale} {scale}"/></asset><worldbody><geom type="mesh" mesh="h"/></worldbody></mujoco>'
    mm2 = mujoco.MjModel.from_xml_string(xml); d2 = mujoco.MjData(mm2); mujoco.mj_forward(mm2, d2)
    R = d2.geom_xmat[0].reshape(3, 3); v = mm2.mesh_vert[: mm2.mesh_vertnum[0]] @ R.T + d2.geom_xpos[0]
    ax = int(np.argmax(v.max(0) - v.min(0))); lo, hi = float(v[:, ax].min()), float(v[:, ax].max()); L = hi - lo
    up = 2   # the section height (z) sets the radius
    # measured on the CAD in thirds (cap 30 %, waist 40 %, cap 30 %) for the radii; the collision then uses short end
    # caps (7 % each, they set the resting height) and the waist radius across the middle, where the fingers (~20 mm
    # wide, wider than the 17.6 mm waist) close: on the real prop they close on the banded waist, caps outside them
    cuts = [lo, lo + 0.3 * L, lo + 0.7 * L, hi]
    radii = []
    for a, b in zip(cuts[:-1], cuts[1:]):
        sel = v[(v[:, ax] >= a - 1e-6) & (v[:, ax] <= b + 1e-6)]
        radii.append(float((sel[:, up].max() - sel[:, up].min()) / 2) if len(sel) else None)
    if radii[1] is None:   # the convex hull has no vertex in the waist: take the waist from the visual mesh (round, 17 mm at 0.65)
        xv = xml.replace("resistor_hull.msh", "resistor_body.msh"); mv = mujoco.MjModel.from_xml_string(xv); dv = mujoco.MjData(mv); mujoco.mj_forward(mv, dv)
        vv = mv.mesh_vert[: mv.mesh_vertnum[0]] @ dv.geom_xmat[0].reshape(3, 3).T + dv.geom_xpos[0]
        sel = vv[(vv[:, ax] >= cuts[1]) & (vv[:, ax] <= cuts[2])]
        radii[1] = float((sel[:, up].max() - sel[:, up].min()) / 2)
    cuts = [lo, lo + 0.07 * L, hi - 0.07 * L, hi]
    vols = [np.pi * r * r * (b - a) for r, a, b in zip(radii, cuts[:-1], cuts[1:])]
    out = []
    for r, a, b, vol in zip(radii, cuts[:-1], cuts[1:], vols):
        p0 = [0.0, 0.0, 0.0]; p1 = [0.0, 0.0, 0.0]; p0[ax] = a; p1[ax] = b
        # condim 6 with rolling friction (2 mm): true cylinders would otherwise roll forever where the faceted hull stopped
        out.append(f'type="cylinder" fromto="{p0[0]:.5f} {p0[1]:.5f} {p0[2]:.5f} {p1[0]:.5f} {p1[1]:.5f} {p1[2]:.5f}" size="{r:.5f}" mass="{mass * vol / sum(vols):.5f}" condim="6" friction="0.9 0.01 0.002"')
    return out
